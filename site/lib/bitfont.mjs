export const GLYPH_W = 5;
export const GLYPH_H = 7;

/**
 * A pixel skull, stamped on every generated plate the way a specimen jar gets
 * a hazard label. Drawn with the sockets widening outward at the top and
 * pinching inward at the bottom, which is the whole trick to an angry face.
 */
export const SKULL = [
  '....#####....',
  '..#########..',
  '.###########.',
  '#############',
  '#...#####...#',
  '#....###....#',
  '##...###...##',
  '###..###..###',
  '#####.#.#####',
  '#####...#####',
  '.###########.',
  '..#.#.#.#.#..',
  '..#########..',
];

/** Blend a string-bitmap sprite into an RGB buffer at integer scale. */
export function drawSprite(buf, bufW, bufH, rows, x, y, scale, rgb, alpha = 1) {
  for (let ry = 0; ry < rows.length; ry++) {
    const row = rows[ry];
    for (let rx = 0; rx < row.length; rx++) {
      if (row[rx] !== '#') continue;
      for (let sy = 0; sy < scale; sy++) {
        const py = y + ry * scale + sy;
        if (py < 0 || py >= bufH) continue;
        for (let sx = 0; sx < scale; sx++) {
          const px = x + rx * scale + sx;
          if (px < 0 || px >= bufW) continue;
          const i = (py * bufW + px) * 3;
          buf[i] += (rgb[0] - buf[i]) * alpha;
          buf[i + 1] += (rgb[1] - buf[i + 1]) * alpha;
          buf[i + 2] += (rgb[2] - buf[i + 2]) * alpha;
        }
      }
    }
  }
}

/**
 * Fold accented Latin down to the ASCII the font actually has, so Swedish and
 * Italian entry names do not turn into a row of blanks.
 */
function fold(ch) {
  const map = {
    Å: 'A', Ä: 'A', Á: 'A', À: 'A', Â: 'A', Ã: 'A',
    Ö: 'O', Ó: 'O', Ò: 'O', Ô: 'O', Õ: 'O', Ø: 'O',
    É: 'E', È: 'E', Ê: 'E', Ë: 'E',
    Í: 'I', Ì: 'I', Î: 'I', Ï: 'I',
    Ú: 'U', Ù: 'U', Û: 'U', Ü: 'U',
    Ç: 'C', Ñ: 'N', Ý: 'Y', Œ: 'O', Æ: 'A', ß: 'S',
    '–': '-', '—': '-', '’': "'", '‘': "'", '“': '"', '”': '"', '…': '.',
  };
  return map[ch] ?? ch;
}

export function textWidth(text, scale, tracking = 1) {
  const n = [...text].length;
  return n * (GLYPH_W + tracking) * scale - tracking * scale;
}

/**
 * Blend text into an RGB byte buffer. Deliberately unantialiased: a hard
 * pixel grid reads as a plate stamp rather than as a botched font.
 */
export function drawText(buf, bufW, bufH, text, x, y, scale, rgb, opts = {}) {
  const tracking = opts.tracking ?? 1;
  const alpha = opts.alpha ?? 1;
  let cursor = x;
  for (const rawCh of [...text.toUpperCase()]) {
    const ch = fold(rawCh);
    const glyph = G[ch] ?? G[' '];
    for (let gy = 0; gy < GLYPH_H; gy++) {
      const bits = glyph[gy];
      for (let gx = 0; gx < GLYPH_W; gx++) {
        if (!(bits & (1 << (GLYPH_W - 1 - gx)))) continue;
        for (let sy = 0; sy < scale; sy++) {
          const py = y + gy * scale + sy;
          if (py < 0 || py >= bufH) continue;
          for (let sx = 0; sx < scale; sx++) {
            const px = cursor + gx * scale + sx;
            if (px < 0 || px >= bufW) continue;
            const i = (py * bufW + px) * 3;
            buf[i] = buf[i] + (rgb[0] - buf[i]) * alpha;
            buf[i + 1] = buf[i + 1] + (rgb[1] - buf[i + 1]) * alpha;
            buf[i + 2] = buf[i + 2] + (rgb[2] - buf[i + 2]) * alpha;
          }
        }
      }
    }
    cursor += (GLYPH_W + tracking) * scale;
  }
  return cursor;
}
